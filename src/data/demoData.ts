// ── Time helpers (all demo timestamps are relative to "now") ───────────────
const HOUR = 3_600_000
const DAY = 86_400_000
const hoursAgo  = (n: number) => new Date(Date.now() - n * HOUR).toISOString()
const daysAgo   = (n: number) => new Date(Date.now() - n * DAY).toISOString()
/** A timestamp N days from now at a specific local hour — for realistic call times. */
const at = (daysOffset: number, hour: number, minute = 0) => {
  const d = new Date(Date.now() + daysOffset * DAY)
  d.setHours(hour, minute, 0, 0)
  return d.toISOString()
}
/** Short human date N days from now, for notes — never goes stale. */
const noteDate = (daysFromNow: number) =>
  new Date(Date.now() + daysFromNow * DAY).toLocaleDateString('en-US', { month: 'short', day: 'numeric' })

